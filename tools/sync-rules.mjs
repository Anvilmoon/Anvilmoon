// Copies the game rules (www/js/rules.js, the master copy) to the server (supabase/functions/api/rules.js).
// Run it after every change to rules.js, before deploying the server:   node tools/sync-rules.mjs
// With --check it changes nothing and fails if the server's copy is out of date (npm test does this).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const head = '// GENERATED COPY of www/js/rules.js, made by `node tools/sync-rules.mjs`. Do not edit this file: edit www/js/rules.js.\n';
const want = head + readFileSync(root + 'www/js/rules.js', 'utf8');
const dest = root + 'supabase/functions/api/rules.js';
const lf = (t) => t.replace(/\r\n/g, '\n');   // git may turn line endings into CRLF on Windows
if (process.argv.includes('--check')) {
  if (!existsSync(dest) || lf(readFileSync(dest, 'utf8')) !== lf(want)) { console.error('supabase/functions/api/rules.js is out of date. Run: node tools/sync-rules.mjs'); process.exit(1); }
  console.log('Server rules are up to date.');
} else { writeFileSync(dest, want); console.log('Copied www/js/rules.js to supabase/functions/api/rules.js'); }
